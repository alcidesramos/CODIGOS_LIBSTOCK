#include "CONFIG_PWM_F.h"

void pwm_fast_init()
{

 //salida pines PWM


    TRISB12_bit=0;
    TRISB13_bit=0;
    TRISB14_bit=0;
    TRISB15_bit=0;

  P1TCON=0;  //limpia todos los bits

  P1TPER=12499;  //carga el periodo;

 P1TCONbits.PTEN=1; //Habilita el timer
  P1TCONbits.PTOPS=0B0000; //  POSTPRESCALADOR  DE SALIDA EN CERO   0-16  =0
 
  //PREESCALDOR EN 64
  P1TCONbits.PTCKPS=0B11; //  PREESCALSOR DE ENTRRADA  1  =64

  //SE PUEDEN OPTENER LA MITAD DE LA FREUENCIA SI ESTA EN MODO UP/DOWN
  P1TCONbits.PTMOD=0B00; //  OPERA EN MODO CONTINUO   CONTADOR ASCENDENTE

//MODO DE OPERACION DEL MODULO PWM
   PWM1CON1=0;
 
 PMOD1_bit=1;  //PWM1x1 EN MODO INDEPENDIENTE
 PMOD2_bit=1; // PWM1x2 EN MODO INDEPENDIENTE

   PEN1L_bit=1; // HABILITA SALIDA PWM1L1 COMO PWM
   //PEN1H_bit=1; //  HABILITA SALIDA PWM1H1 COMO PWM
 
   PEN2L_bit=1; // HABILITA SALIDA PWM1L2 COMO PWM
   //PEN2H_bit=1; //  HABILITA SALIDA PWM1H2 COMO PWM


   // SEGUNDO REGISTRO DE CONFIGURACION
   PWM1CON2=0;
   PWM1CON2bits.IUE=1; // ACTUALIZA LOS CICLO UTIL DE INEMDIATO
   
  //LOS PINES  PWM LOS CONTOLA EL MODULO PWM
  POVD1L_bit=1;
  //POVD1H_bit=1;

  POVD2L_bit=1;
  //POVD2H_bit=1;


// POR EL MOMENTO NO SE CONFIGRAN LOS REGISTOS DE TIEMPO MUERTO NI DE FALLAS
 // CARGA EL CICLO UTIL;
  P1DC1=1249;
  P1DC2=12449; //CICLO UTIL AL 50%






}